//! Renderer-specific artifacts derived from the same project theme as iced.
use crate::{ThemeMode, ThemeSelection};
use serde::Serialize;

#[derive(Debug, Clone, Serialize)]
pub struct DesktopTheme {
    pub hyprland: String,
    pub sway: String,
    pub css: String,
    pub foot: String,
}
fn hex(rgb: [u8; 3]) -> String {
    format!("{:02x}{:02x}{:02x}", rgb[0], rgb[1], rgb[2])
}
impl ThemeSelection {
    pub fn desktop_artifacts(self) -> DesktopTheme {
        let p = self.palette();
        let m = self.metrics();
        let mut hyprland =
            String::from("# Generated by dockctl desktop-theme from the project theme.\n");
        for (name, color) in [
            ("background", p.background),
            ("surface", p.surface),
            ("text", p.text),
            ("border", p.border),
            ("accent", p.primary),
        ] {
            hyprland.push_str(&format!("$coherence_{name} = rgba({}ff)\n", hex(color)));
        }
        hyprland.push_str(&format!(
            "$coherence_gap = {}\n$coherence_radius = {}\n",
            m.space_2, m.radius
        ));
        // Applying variables alone does not reapply already-parsed Hyprland options.
        hyprland.push_str("general {\n    col.active_border = $coherence_accent\n    col.inactive_border = $coherence_border\n    gaps_in = $coherence_gap\n    gaps_out = $coherence_gap\n}\ndecoration {\n    rounding = $coherence_radius\n}\n");
        // Terminal ANSI roles map to canonical semantic roles.
        let ansi = [
            p.background,
            p.danger,
            p.success,
            p.warning,
            p.primary,
            p.primary,
            p.info,
            p.text,
        ];
        let mut foot = format!(
            "# Generated by dockctl desktop-theme from the project theme.\n[main]\nfont=monospace:size={}\npad={}x{}\n\n[colors]\nbackground={}\nforeground={}\nselection-background={}\nselection-foreground={}\n",
            m.small,
            m.space_2,
            m.space_2,
            hex(p.background),
            hex(p.text),
            hex(p.primary),
            hex(p.background)
        );
        for (i, color) in ansi.into_iter().enumerate() {
            foot.push_str(&format!(
                "regular{i}={}\nbright{i}={}\n",
                hex(color),
                hex(color)
            ));
        }
        let sway = format!(
            "# Generated from the project theme.\nclient.focused #{accent} #{surface} #{text} #{accent} #{accent}\nclient.unfocused #{border} #{surface} #{text} #{border} #{border}\nclient.focused_inactive #{border} #{surface} #{text} #{border} #{border}\noutput * bg #{background} solid_color\ngaps inner {gap}\ngaps outer {gap}\n",
            accent = hex(p.primary),
            surface = hex(p.surface),
            text = hex(p.text),
            border = hex(p.border),
            background = hex(p.background),
            gap = m.space_2
        );
        let mode = match self.mode() {
            ThemeMode::Dark => "dark",
            ThemeMode::Light => "light",
        };
        let css = format!(
            "/* Generated from the project theme by dockctl export-desktop. */\n:root {{ color-scheme: {mode}; --background: #{background}; --surface: #{surface}; --text: #{text}; --muted: #{muted}; --accent: #{accent}; --border: #{border}; }}\n",
            background = hex(p.background),
            surface = hex(p.surface),
            text = hex(p.text),
            muted = hex(p.text_muted),
            accent = hex(p.primary),
            border = hex(p.border)
        );
        DesktopTheme {
            hyprland,
            sway,
            css,
            foot,
        }
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Accent, Catalog};
    #[test]
    fn linux_and_iced_share_project_colors_and_geometry() {
        for project in Catalog::bundled().unwrap().projects {
            let theme = project.theme;
            let artifacts = theme.desktop_artifacts();
            let palette = theme.palette();
            assert!(
                artifacts
                    .css
                    .contains(&format!("--accent: #{}", hex(palette.primary)))
            );
            assert!(
                artifacts
                    .css
                    .contains(&format!("--background: #{}", hex(palette.background)))
            );
            assert!(
                artifacts
                    .sway
                    .contains(&format!("client.focused #{}", hex(palette.primary)))
            );
            assert!(artifacts.sway.contains(&format!(
                "output * bg #{} solid_color",
                hex(palette.background)
            )));
            assert!(artifacts.hyprland.contains(&format!(
                "$coherence_accent = rgba({}ff)",
                hex(palette.primary)
            )));
            assert!(
                artifacts
                    .foot
                    .contains(&format!("background={}", hex(palette.background)))
            );
            assert!(
                artifacts
                    .hyprland
                    .contains(&format!("$coherence_gap = {}", theme.metrics().space_2))
            );
        }
    }
    #[test]
    fn generation_is_deterministic_and_themes_differ() {
        let dark = ThemeSelection::Coherence {
            mode: ThemeMode::Dark,
            accent: Accent::Info,
        };
        let light = ThemeSelection::Coherence {
            mode: ThemeMode::Light,
            accent: Accent::Brand,
        };
        assert_eq!(
            dark.desktop_artifacts().hyprland,
            dark.desktop_artifacts().hyprland
        );
        assert_ne!(
            dark.desktop_artifacts().foot,
            light.desktop_artifacts().foot
        );
    }
}
