fn cli() -> Command {
    Command::new(env!("CARGO_BIN_EXE_canvas-model-host"))
}

/// Run a CLI command with a hard deadline. A hung scene is a test failure, not
/// a hung test suite.
fn run_bounded(mut command: Command, deadline: Duration) -> Output {
    let mut child: Child = command
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn canvas-model-host");
    let started = Instant::now();
    loop {
        if child.try_wait().expect("poll child").is_some() {
            return child.wait_with_output().expect("collect output");
        }
        if started.elapsed() > deadline {
            let _ = child.kill();
            let _ = child.wait();
            panic!("canvas-model-host hung for more than {deadline:?}");
        }
        std::thread::sleep(Duration::from_millis(10));
    }
}

fn scene_command(
    runtime: &str,
    scene: &Path,
    context: &SceneContext,
) -> (Command, tempfile::TempDir) {
    let assets = tempfile::tempdir().expect("tempdir");
    for name in &context.steps {
        std::fs::write(assets.path().join(name), b"solid\n").expect("write mesh");
    }
    let mut command = cli();
    command.args([
        runtime,
        "scene",
        &scene.display().to_string(),
        "--assets",
        &assets.path().display().to_string(),
        "--json",
    ]);
    (command, assets)
}

/// The new shape returns the same bytes and exit code for both runtimes.
#[test]
fn cli_scene_shape_matches_for_lua_and_wasm() {
    let context = assets();
    let (wasm_command, _wasm_assets) =
        scene_command("wasm", &fixture("scenes/field-orbit.wasm"), &context);
    let wasm = run_bounded(wasm_command, Duration::from_secs(20));
    assert_eq!(
        wasm.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&wasm.stderr)
    );
    let mut expected = FIELD_ORBIT_GOLDEN.to_vec();
    expected.push(b'\n');
    assert_eq!(
        wasm.stdout, expected,
        "wasm CLI output must be the golden scene"
    );

    let (lua_command, _lua_assets) =
        scene_command("lua", &fixture("scenes/field-orbit.lua"), &context);
    let lua = run_bounded(lua_command, Duration::from_secs(20));
    assert_eq!(
        lua.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&lua.stderr)
    );
    assert_eq!(
        lua.stdout, wasm.stdout,
        "runtimes must print identical JSON"
    );
}

/// Usage mistakes are exit 2, not a runtime failure.
#[test]
fn cli_usage_errors_exit_two() {
    let cases = vec![
        vec!["wasm", "scene"],
        vec!["wasm", "scene", "scene.wasm", "--json"],
        vec!["wasm", "scene", "scene.wasm", "--assets"],
        vec![
            "wasm",
            "scene",
            "scene.wasm",
            "--assets",
            ".",
            "--fuel",
            "lots",
        ],
        vec!["wasm", "scene", "scene.wasm", "--assets", ".", "--invented"],
        vec!["python", "scene", "scene.py", "--assets", "."],
        vec!["only", "seven", "args", "for", "the", "stream", "form"],
    ];
    for args in cases {
        let mut command = cli();
        command.args(&args);
        let output = run_bounded(command, Duration::from_secs(10));
        assert_eq!(
            output.status.code(),
            Some(2),
            "args {args:?}: stdout={} stderr={}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }
}

