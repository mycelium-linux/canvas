//! Acceptance tests for the logic-only WASM scene path.
//!
//! The committed fixtures are a Lua scene and a hand-written WAT module that
//! express the same scene. The parity tests compare their canonical
//! serialization byte-for-byte against a golden file, so drift is a diff
//! rather than a judgement call.

use canvas_model_host::{
    SceneContext, lua,
    wasm::{self, SceneError},
};
use std::{
    path::{Path, PathBuf},
    process::{Child, Command, Output, Stdio},
    time::{Duration, Instant},
};

fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join(name)
}

fn assets() -> SceneContext {
    SceneContext::scan(&fixture("assets"))
}

fn evaluate_lua(name: &str, context: &SceneContext) -> canvas_model_host::SceneState {
    let source =
        std::fs::read_to_string(fixture(&format!("scenes/{name}.lua"))).expect("read lua fixture");
    lua::evaluate_with(&source, context).expect("lua fixture evaluates")
}

fn evaluate_wasm(name: &str, context: &SceneContext) -> wasm::SceneRun {
    wasm::evaluate_file(&fixture(&format!("scenes/{name}.wasm")), context)
        .expect("wasm fixture evaluates")
}

fn canonical(scene: &canvas_model_host::SceneState) -> Vec<u8> {
    serde_json::to_vec(scene).expect("scene serializes")
}

/// The committed golden for a three-step build, generated by the same
/// `serde_json::to_vec` used in production, not by hand.
const FIELD_ORBIT_GOLDEN: &[u8] = include_bytes!("fixtures/scenes/field-orbit.golden.json");
const FOLLOW_LATEST_GOLDEN: &[u8] = include_bytes!("fixtures/scenes/follow-latest.golden.json");

/// Both runtimes receive the same assets and must produce the identical scene
/// bytes, and those bytes must match the checked-in golden.
#[test]
fn golden_field_orbit_scene_is_byte_identical_across_runtimes() {
    let context = assets();
    let lua_scene = evaluate_lua("field-orbit", &context);
    let wasm_scene = evaluate_wasm("field-orbit", &context).scene;

    let lua_bytes = canonical(&lua_scene);
    let wasm_bytes = canonical(&wasm_scene);
    assert_eq!(
        wasm_bytes, lua_bytes,
        "wasm and lua must serialize the same SceneState"
    );
    assert_eq!(
        wasm_bytes.as_slice(),
        FIELD_ORBIT_GOLDEN,
        "golden field-orbit scene drifted"
    );
    assert!(wasm_scene.validate().is_ok());
}

/// The follow-the-build scene must agree for an empty build, a partial build,
/// and the committed three-step build. The golden pins the three-step case.
#[test]
fn golden_follow_latest_scene_is_byte_identical_across_runtimes() {
    let empty = tempfile::tempdir().expect("tempdir");
    let partial = tempfile::tempdir().expect("tempdir");
    for name in ["step-0.stl", "step-1.stl"] {
        std::fs::write(partial.path().join(name), b"solid\n").expect("write mesh");
    }

    for (index, context) in [
        assets(),
        SceneContext::scan(partial.path()),
        SceneContext::scan(empty.path()),
    ]
    .into_iter()
    .enumerate()
    {
        let lua_scene = evaluate_lua("follow-latest", &context);
        let wasm_scene = evaluate_wasm("follow-latest", &context).scene;
        assert_eq!(
            canonical(&wasm_scene),
            canonical(&lua_scene),
            "context {index}: wasm and lua disagree: {context:?}"
        );
        if index == 0 {
            assert_eq!(
                canonical(&wasm_scene).as_slice(),
                FOLLOW_LATEST_GOLDEN,
                "golden follow-latest scene drifted"
            );
        }
    }
}

/// A scene that imports *anything* is rejected before it runs: with no host
/// imports there is no filesystem, clock, network or GPU surface to reach.
#[test]
fn a_module_with_host_imports_is_rejected() {
    let wat_source = r#"
    (module
      (import "env" "now" (func (result i64)))
      (memory (export "memory") 1)
      (func (export "alloc") (param $len i32) (result i32) (i32.const 0))
      (func (export "scene") (param $ptr i32) (param $len i32) (result i32) (i32.const 0)))
    "#;
    let dir = tempfile::tempdir().expect("tempdir");
    let path = write_module(dir.path(), "imports.wasm", wat_source);
    let error = wasm::evaluate_file(&path, &SceneContext::default()).expect_err("must reject");
    assert_code(&error, "host_imports");
    let message = format!("{error:#}");
    assert!(
        message.contains("import"),
        "error should name the imports: {message}"
    );
    assert!(
        message.contains(&path.display().to_string()),
        "error should name the scene path: {message}"
    );
}

/// Fuel is the deterministic limit; an endless loop must fail fast instead of
/// hanging the host's frame loop.
#[test]
fn fuel_exhaustion_is_its_own_error() {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = write_module(dir.path(), "spin.wasm", infinite_loop_module());
    let started = Instant::now();
    let error = wasm::evaluate_file(&path, &SceneContext::default()).expect_err("must stop");
    assert_code(&error, "fuel_exhausted");
    assert!(
        format!("{error:#}").to_lowercase().contains("fuel"),
        "error should name fuel: {error:#}"
    );
    assert!(
        started.elapsed() < Duration::from_secs(10),
        "a runaway scene must not hold the host"
    );
}

/// The epoch deadline is a second backstop. This test gives the module so much
/// fuel that fuel cannot be what stops it, so only the epoch ticker can.
#[test]
fn epoch_timeout_is_its_own_error() {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = write_module(dir.path(), "epoch.wasm", infinite_loop_module());
    let started = Instant::now();
    let error = wasm::evaluate_file_with_fuel(&path, &SceneContext::default(), u64::MAX)
        .expect_err("must stop");
    assert_code(&error, "epoch_timeout");
    assert!(
        format!("{error:#}").to_lowercase().contains("epoch"),
        "error should name the epoch deadline: {error:#}"
    );
    assert!(
        started.elapsed() < Duration::from_secs(5),
        "the epoch deadline must fire in about a second, took {:?}",
        started.elapsed()
    );
}

/// The linear-memory cap is real: a scene that tries to grow past 8 MiB fails
/// with a memory error, not a generic guest trap.
#[test]
fn memory_limit_is_its_own_error() {
    let wat_source = r#"
    (module
      (memory (export "memory") 1)
      (func (export "alloc") (param $len i32) (result i32) (i32.const 0))
      (func (export "scene") (param $ptr i32) (param $len i32) (result i32)
        (local $page i32)
        (block $all
          (loop $grow
            (br_if $all (i32.ge_s (local.get $page) (i32.const 256)))
            (if (i32.eq (memory.grow (i32.const 1)) (i32.const -1))
              (then (unreachable)))
            (local.set $page (i32.add (local.get $page) (i32.const 1)))
            (br $grow)))
        (i32.const 0)))
    "#;
    let dir = tempfile::tempdir().expect("tempdir");
    let path = write_module(dir.path(), "greedy.wasm", wat_source);
    let error = wasm::evaluate_file(&path, &SceneContext::default()).expect_err("must stop");
    assert_code(&error, "memory_limit");
    assert!(
        format!("{error:#}").to_lowercase().contains("memory"),
        "error should name memory: {error:#}"
    );
}

/// Each missing ABI export names itself, so a scene author knows what to add.
#[test]
fn a_wrong_abi_names_the_missing_export() {
    let dir = tempfile::tempdir().expect("tempdir");
    let cases = [
        (
            "missing-memory.wasm",
            r#"
            (module
              (func (export "alloc") (param $len i32) (result i32) (i32.const 0))
              (func (export "scene") (param $ptr i32) (param $len i32) (result i32) (i32.const 0)))
            "#,
            "memory",
        ),
        (
            "missing-alloc.wasm",
            r#"
            (module
              (memory (export "memory") 1)
              (func (export "scene") (param $ptr i32) (param $len i32) (result i32) (i32.const 0)))
            "#,
            "alloc",
        ),
        (
            "missing-scene.wasm",
            r#"
            (module
              (memory (export "memory") 1)
              (func (export "alloc") (param $len i32) (result i32) (i32.const 0)))
            "#,
            "scene",
        ),
    ];
    for (name, source, missing) in cases {
        let path = write_module(dir.path(), name, source);
        let error = wasm::evaluate_file(&path, &SceneContext::default()).expect_err("must reject");
        assert_code(&error, "wrong_abi");
        let message = format!("{error:#}").to_lowercase();
        assert!(
            message.contains(missing),
            "error should name `{missing}`: {message}"
        );
    }
}

/// Oversized modules are refused before compilation, with a distinct error.
