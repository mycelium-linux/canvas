/// The fail-closed table: every limit and validation failure exits 1 with a
/// distinct message, and none of them panics or hangs.
#[test]
fn cli_limit_failures_exit_one_with_distinct_errors() {
    let dir = tempfile::tempdir().expect("tempdir");
    let context = SceneContext::default();
    let mut cases: Vec<(&str, PathBuf, Option<u64>, &str)> = Vec::new();

    cases.push((
        "fuel",
        write_module(dir.path(), "cli-fuel.wasm", infinite_loop_module()),
        None,
        "fuel",
    ));
    cases.push((
        "epoch",
        write_module(dir.path(), "cli-epoch.wasm", infinite_loop_module()),
        Some(u64::MAX),
        "epoch deadline",
    ));
    let grow = r#"
    (module
      (memory (export "memory") 1)
      (func (export "alloc") (param $len i32) (result i32) (i32.const 0))
      (func (export "scene") (param $ptr i32) (param $len i32) (result i32)
        (block $done
          (loop $grow
            (br_if $done (i32.eq (memory.grow (i32.const 1)) (i32.const -1)))
            (br $grow)))
        (unreachable)))
    "#;
    cases.push((
        "memory",
        write_module(dir.path(), "cli-memory.wasm", grow),
        None,
        "memory limit",
    ));
    let magic = dir.path().join("cli-magic.wasm");
    std::fs::write(&magic, b"not wasm at all").expect("write garbage");
    cases.push(("magic", magic, None, "bad magic"));
    let abi = r#"
    (module
      (memory (export "memory") 1)
      (func (export "alloc") (param $len i32) (result i32) (i32.const 0)))
    "#;
    cases.push((
        "abi",
        write_module(dir.path(), "cli-abi.wasm", abi),
        None,
        "ABI is incomplete",
    ));
    let oversized = dir.path().join("cli-oversized.wasm");
    let mut bytes = vec![0u8; wasm::MAX_MODULE_BYTES + 1];
    bytes[..4].copy_from_slice(b"\0asm");
    std::fs::write(&oversized, bytes).expect("write oversized module");
    cases.push(("oversized", oversized, None, "too large"));

    for (name, path, fuel, expected) in cases {
        let (mut command, _assets) = scene_command("wasm", &path, &context);
        if let Some(fuel) = fuel {
            command.args(["--fuel", &fuel.to_string()]);
        }
        let output = run_bounded(command, Duration::from_secs(20));
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert_eq!(output.status.code(), Some(1), "{name}: stderr={stderr}");
        let lower = stderr.to_lowercase();
        assert!(
            lower.contains(&expected.to_lowercase()),
            "{name}: expected {expected:?} in stderr: {stderr}"
        );
        assert!(
            !lower.contains("panicked"),
            "{name}: must fail closed, not panic: {stderr}"
        );
    }
}
